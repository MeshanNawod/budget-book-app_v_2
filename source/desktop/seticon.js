const ResEdit = require('resedit'), fs = require('fs');
const exePath = process.argv[2], data = fs.readFileSync(exePath);
const exe = ResEdit.NtExecutable.from(data, { ignoreCert: true });
const res = ResEdit.NtExecutableResource.from(exe);
const ico = ResEdit.Data.IconFile.from(fs.readFileSync('build/icon.ico'));
const groups = ResEdit.Resource.IconGroupEntry.fromEntries(res.entries);
const gid = groups.length ? groups[0].id : 1, lang = groups.length ? groups[0].lang : 1033;
ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries, gid, lang, ico.icons.map(i => i.data));
const vi = ResEdit.Resource.VersionInfo.fromEntries(res.entries)[0];
const L = { lang: 1033, codepage: 1200 };
vi.setStringValues(L, { FileDescription: 'Budget Book', ProductName: 'Budget Book', CompanyName: 'Budget Book', InternalName: 'Budget Book', OriginalFilename: 'Budget Book.exe', LegalCopyright: 'Budget Book' });
vi.setFileVersion(1, 1, 0, 0, 1033); vi.setProductVersion(1, 1, 0, 0, 1033);
vi.outputToResourceEntries(res.entries);
res.outputResource(exe);
fs.writeFileSync(exePath, Buffer.from(exe.generate()));
console.log('icon + version set; integrity entries:', res.entries.filter(e => String(e.type) === '10').length);
